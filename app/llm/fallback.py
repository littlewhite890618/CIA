"""對話生成失敗時的降級回應（task 5.5）。

規格要求「以不破壞人設的方式回應使用者」。這條線不能退讓——
免費模型的速率上限低，失敗是常態（design.md 第三項外部約束），
若失敗時讓使用者看到系統錯誤訊息或乾脆已讀不回，角色就穿幫了。

**設計原則：降級語句必須是「人會說的話」，而且對任何人設都成立。**
所以這裡只放「恍神了、沒聽清楚」這類通用的日常搪塞，不放任何
帶特定語氣或口頭禪的句子——那些會跟人設卡打架。

已知限制：這批句子與人設卡無關，晴晴講起來會略顯中性。
Phase 1 應把降級語句移進人設卡（新增 runtime 以外的 fallback 欄位），
讓每個角色有自己的搪塞方式。POC 階段不值得為此擴充卡片結構。
"""

from __future__ import annotations

import random

# 共通原則：短、口語、把話丟回給對方，讓對話能繼續而不是停在這裡。
# 不道歉（「抱歉系統忙碌」一聽就是機器人），不解釋原因。
DIALOG_FALLBACKS = (
    "欸我剛剛恍神了一下，你剛說什麼？",
    "等我一下下，我這邊有點忙 🥺",
    "嗯…我想一下要怎麼說",
    "剛剛沒看清楚，你再說一次好不好",
)


def pick_fallback(rng: random.Random | None = None) -> str:
    """挑一句降級回應。

    隨機而非固定，是因為模型失敗可能連續發生——每次都回同一句，
    使用者馬上就會發現那是罐頭訊息。
    """
    rng = rng or random.Random()
    return rng.choice(DIALOG_FALLBACKS)
